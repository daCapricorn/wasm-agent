//! Compare source compilation and local serialized artifacts in fresh processes.
//! Only load artifacts created by this executable in its private temporary directory.
use anyhow::{ensure, Context, Result};
use clap::Parser;
use serde_json::{json, Value};
use std::{
    path::PathBuf,
    sync::{Arc, Mutex},
    time::{Duration, Instant},
};
use wasm_agent::composition::{Composition, Packet, Session};
use wasmer::Module;
use wasmer_wasix::{runtime::task_manager::tokio::TokioTaskManager, PluggableRuntime, Runtime};

#[derive(Parser)]
struct Args {
    #[arg(long, default_value_t = 5)]
    runs: usize,
    #[arg(long, hide = true)]
    worker: Option<String>,
    /// Internal worker input: executable artifacts generated by this benchmark only.
    #[arg(long, hide = true)]
    trusted_artifacts: Option<PathBuf>,
}

fn config() -> Result<Composition> {
    Composition::load(PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("configs/agent-scripted.json"))
}
fn ms(start: Instant) -> f64 {
    start.elapsed().as_secs_f64() * 1000.0
}

fn main() -> Result<()> {
    let args = Args::parse();
    ensure!(
        (1..=50).contains(&args.runs),
        "runs must be between 1 and 50"
    );
    let runtime = tokio::runtime::Builder::new_multi_thread()
        .enable_all()
        .build()?;
    let result = runtime.block_on(async {
        if let Some(mode) = args.worker {
            worker(&mode, args.trusted_artifacts).await
        } else {
            parent(args.runs)
        }
    });
    runtime.shutdown_timeout(Duration::from_secs(2));
    result
}

fn parent(runs: usize) -> Result<()> {
    let directory = tempfile::tempdir()?;
    let prepare = Instant::now();
    let mut preparation = Vec::new();
    for (name, spec) in config()?.modules {
        let engine = PluggableRuntime::new(Arc::new(TokioTaskManager::default())).engine();
        let wasm = std::fs::read(&spec.path)?;
        let wasm_bytes = wasm.len();
        let compile = Instant::now();
        let module = Module::new(&engine, wasm)?;
        let compile_ms = ms(compile);
        let serialize = Instant::now();
        let artifact = module.serialize()?;
        let artifact_bytes = artifact.len();
        let file = PathBuf::from(spec.path).file_name().unwrap().to_owned();
        std::fs::write(directory.path().join(file), &artifact)?;
        preparation.push(json!({"name":name,"compile_ms":compile_ms,"serialize_write_ms":ms(serialize),"wasm_bytes":wasm_bytes,"artifact_bytes":artifact_bytes}));
    }
    println!(
        "{}",
        json!({"phase":"prepare","total_ms":ms(prepare),"modules":preparation})
    );
    let exe = std::env::current_exe()?;
    let mut samples = Vec::<Value>::new();
    for run in 0..runs {
        let modes = if run % 2 == 0 {
            ["jit", "precompiled"]
        } else {
            ["precompiled", "jit"]
        };
        for mode in modes {
            // A fresh OS process has no in-memory Wasmer modules from the compiler process.
            let start = Instant::now();
            let result = std::process::Command::new(&exe)
                .args(["--worker", mode, "--trusted-artifacts"])
                .arg(directory.path())
                .output()?;
            ensure!(
                result.status.success(),
                "worker failed: {}",
                String::from_utf8_lossy(&result.stderr)
            );
            let mut sample: Value = serde_json::from_slice(&result.stdout)?;
            sample["run"] = json!(run + 1);
            sample["process_total_ms"] = json!(ms(start));
            println!("{sample}");
            samples.push(sample);
        }
    }
    for mode in ["jit", "precompiled"] {
        let mut summary = json!({"phase":"median","mode":mode,"runs":runs});
        for field in [
            "startup_ms",
            "load_ms",
            "first_turn_ms",
            "recall_ms",
            "shutdown_ms",
            "process_total_ms",
        ] {
            let mut values: Vec<f64> = samples
                .iter()
                .filter(|s| s["mode"] == mode)
                .map(|s| s[field].as_f64().unwrap())
                .collect();
            values.sort_by(f64::total_cmp);
            summary[field] = json!((values[(runs - 1) / 2] + values[runs / 2]) / 2.0);
        }
        println!("{summary}");
    }
    Ok(())
}

async fn worker(mode: &str, directory: Option<PathBuf>) -> Result<()> {
    ensure!(mode == "jit" || mode == "precompiled", "unknown mode");
    let compiled = mode == "precompiled";
    let directory = directory.context("missing artifact directory")?;
    let times = Arc::new(Mutex::new(Vec::<Value>::new()));
    let record = times.clone();
    let config = config()?;
    let start = Instant::now();
    let mut session = Session::start_with_loader(config, move |engine, path| {
        let start = Instant::now();
        let name = path.file_name().context("module filename")?;
        let source = if compiled {
            directory.join(name)
        } else {
            path.to_path_buf()
        };
        let bytes = std::fs::read(source)?;
        let module = if compiled {
            // SAFETY: internal workers load only freshly serialized artifacts produced
            // by this same executable on this machine in the parent's private tempdir.
            // This is deliberately NOT enabled for arbitrary files in user compositions.
            unsafe { Module::deserialize(engine, bytes)? }
        } else {
            Module::new(engine, bytes)?
        };
        record
            .lock()
            .unwrap()
            .push(json!({"module":name.to_string_lossy(),"load_ms":ms(start)}));
        Ok(module)
    })
    .await?;
    let startup_ms = ms(start);
    let first = Instant::now();
    let answer = turn(&mut session, "one", "add 17 25").await?;
    let first_turn_ms = ms(first);
    ensure!(
        answer["text"] == "result: 42.0" && answer["tool_calls"] == 1 && answer["messages"] == 4,
        "invalid first response: {answer}"
    );
    let recall = Instant::now();
    let answer = turn(&mut session, "two", "recall").await?;
    let recall_ms = ms(recall);
    ensure!(
        answer["text"] == "result: 42.0" && answer["tool_calls"] == 0 && answer["messages"] == 6,
        "invalid recall: {answer}"
    );
    let mut saw_tool = false;
    while let Ok(route) = session.traces.try_recv() {
        saw_tool |= route.to == "tool" && route.method == "add";
    }
    ensure!(saw_tool, "tool WASM was not called");
    let stop = Instant::now();
    session.stop().await?;
    let loads = times.lock().unwrap();
    let load_ms: f64 = loads.iter().map(|v| v["load_ms"].as_f64().unwrap()).sum();
    println!(
        "{}",
        json!({"phase":"sample","mode":mode,"startup_ms":startup_ms,"load_ms":load_ms,"first_turn_ms":first_turn_ms,"recall_ms":recall_ms,"shutdown_ms":ms(stop),"modules":*loads,"verified":true})
    );
    Ok(())
}

async fn turn(session: &mut Session, id: &str, text: &str) -> Result<Value> {
    session
        .send(Packet::request(
            &session.entry,
            id,
            "turn",
            json!({"text":text}),
        ))
        .await?;
    let packet = tokio::time::timeout(Duration::from_secs(10), session.events.recv())
        .await?
        .context("session ended")??;
    ensure!(
        packet.id == id && packet.error.is_none(),
        "turn failed: {packet:?}"
    );
    Ok(packet.body)
}
